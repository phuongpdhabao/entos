        }

        public static async System.Threading.Tasks.Task<string> YoutubeTranscript(string videoUrl, string saveFile)
        {
            var videoId = YoutubeExplode.Videos.VideoId.TryParse(videoUrl);
            if (videoId is null)
                return null;
            var youTubeTranscriptApi = new YoutubeTranscriptApi.YouTubeTranscriptApi();
            try
            {
                var transcriptItems = youTubeTranscriptApi.GetTranscript(videoId, new[] { "en", "vi" });
                if (transcriptItems.Count() > 0)
                {
                    string subtitleText = "";
                    //var subtitleWithSort = video.AudioList.OrderBy(m => m.Start);
                    int index = 1;
                    foreach (var transcriptItem in transcriptItems)
                    {
                        var textValue = transcriptItem.Text;
                        if (!string.IsNullOrEmpty(textValue) && transcriptItem.Start > 0)
                        {
                            subtitleText += index.ToString("D");
                            subtitleText += System.Environment.NewLine;
                            subtitleText += string.Format("{0} --> {1}", System.TimeSpan.FromMilliseconds(transcriptItem.Start).ToString(@"hh\:mm\:ss\,fff"), System.TimeSpan.FromMilliseconds(transcriptItem.Start + transcriptItem.Duration).ToString(@"hh\:mm\:ss\,fff"));
                            subtitleText += System.Environment.NewLine;
                            subtitleText += textValue;
                            subtitleText += System.Environment.NewLine;
                            subtitleText += System.Environment.NewLine;
                            index++;
                        }
                    }
                    if (!string.IsNullOrEmpty(subtitleText))
                    {
                        System.IO.File.WriteAllText(saveFile, subtitleText);
                        return saveFile;
                    }
                }

            }
            catch (System.Exception)
            {

            }
            return null;
        }

        /// <summary>
        /// Kiểm tra URL có phải là YouTube không
        /// </summary>
        /// <param name="url">URL cần kiểm tra</param>
        /// <returns>True nếu là URL YouTube</returns>
        public static bool IsYoutubeUrl(string url)
        {
            if (!string.IsNullOrEmpty(url))
            {
                if (url.Contains("youtube.com", StringComparison.OrdinalIgnoreCase) || url.Contains("youtu.be", StringComparison.OrdinalIgnoreCase))
                    return true;
            }
            return false;


        }


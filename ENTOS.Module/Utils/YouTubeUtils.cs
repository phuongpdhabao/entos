        public static async System.Threading.Tasks.Task<string> DownloadFromYoutubeAsync(string videoUrl, string saveFolder, bool? isVideo = true, bool? subtitle = null, bool isAutoGenerated = false, string languageCode = "en")
        {
            var youtube = new YoutubeExplode.YoutubeClient();
            var videoId = YoutubeExplode.Videos.VideoId.Parse(videoUrl);
            var videoYoutube = await youtube.Videos.GetAsync(videoId);
            if (subtitle != null)
            {
                var trackManifest = await youtube.Videos.ClosedCaptions.GetManifestAsync(videoUrl);
                if (trackManifest.Tracks.FirstOrDefault(x => !x.IsAutoGenerated) == null && !isAutoGenerated)
                {
                    subtitle = false;
                }
                //2025-05-31: Lấy phụ đề tùy theo lựa chọn
                var trackInfo = trackManifest.Tracks?.FirstOrDefault(x => !x.IsAutoGenerated && x.Language.Code.StartsWith(languageCode));
                if (!isAutoGenerated && trackInfo == null && trackManifest != null)
                {
                    subtitle = false;
                }
                if (isAutoGenerated)
                    trackInfo = trackManifest.Tracks?.FirstOrDefault(x => x.IsAutoGenerated);

                if (subtitle == false)
                {
                    if (trackInfo != null)
                        return trackInfo.Url;
                    else return null;
                }
                if (subtitle == true)
                {
                    if (trackInfo is null)
                        trackInfo = trackManifest.Tracks?.FirstOrDefault();
                    if (trackInfo != null)
                    {
                        var subTitlePath = $"{saveFolder}\\{Module.Helpers.FileSystemHelper.GetValidFileName(videoYoutube.Title).Replace("   ", " ").Replace("  ", " ")}.srt";
                        await youtube.Videos.ClosedCaptions.DownloadAsync(trackInfo, subTitlePath);
                        return subTitlePath;
                    }
                }

                return null;
            }
            var streamManifest = await youtube.Videos.Streams.GetManifestAsync(videoId);
            //var streamInfo = streamManifest.GetMuxedStreams().GetWithHighestVideoQuality();
            if (isVideo == null)
            {
                var videoStreamInfo = streamManifest.GetVideoStreams().Where(s => s.Container == YoutubeExplode.Videos.Streams.Container.Mp4).GetWithHighestVideoQuality();
                // Get the actual stream
                var videostream = await youtube.Videos.Streams.GetAsync(videoStreamInfo);
                var videoPath = $"{saveFolder}\\{Module.Helpers.FileSystemHelper.GetValidFileName(videoYoutube.Title).Replace("   ", " ").Replace("  ", " ")}-Video.{videoStreamInfo.Container}";
                await youtube.Videos.Streams.DownloadAsync(videoStreamInfo, videoPath);
                return videoPath;
            }
            else if (isVideo == false)
            {
                var audioStreamInfo = streamManifest.GetAudioOnlyStreams().Where(s => s.Container == YoutubeExplode.Videos.Streams.Container.Mp4 || s.Container == YoutubeExplode.Videos.Streams.Container.Mp3).GetWithHighestBitrate();
                // Get the actual stream
                var audiostream = await youtube.Videos.Streams.GetAsync(audioStreamInfo);
                var audioPath = $"{saveFolder}\\{Module.Helpers.FileSystemHelper.GetValidFileName(videoYoutube.Title).Replace("   ", " ").Replace("  ", " ")}-Audio.{audioStreamInfo.Container}";
                await youtube.Videos.Streams.DownloadAsync(audioStreamInfo, audioPath);
                return audioPath;
            }
            else
            {
                //video
                var videoStreamInfo = streamManifest.GetVideoStreams().Where(s => s.Container == YoutubeExplode.Videos.Streams.Container.Mp4).GetWithHighestVideoQuality();
                var videostream = await youtube.Videos.Streams.GetAsync(videoStreamInfo);
                var videoPath = $"{saveFolder}\\{Module.Helpers.FileSystemHelper.GetValidFileName(videoYoutube.Title).Replace("   ", " ").Replace("  ", " ")}.{videoStreamInfo.Container}";
                //audio
                var audioStreamInfo = streamManifest.GetAudioOnlyStreams().Where(s => s.Container == YoutubeExplode.Videos.Streams.Container.Mp4 || s.Container == YoutubeExplode.Videos.Streams.Container.Mp3).GetWithHighestBitrate();
                var audiostream = await youtube.Videos.Streams.GetAsync(audioStreamInfo);
                //var audioPath = $"{saveFolder}\\{videoYoutube.Title}.{audioStreamInfo.Container}";
                //Trộn 2 luồng               
                var streamInfos = new YoutubeExplode.Videos.Streams.IStreamInfo[] { audioStreamInfo, videoStreamInfo };

                await youtube.Videos.DownloadAsync(streamInfos, new YoutubeExplode.Converter.ConversionRequestBuilder(videoPath).Build());
                return videoPath;
            }
            //var trackManifest = await youtube.Videos.ClosedCaptions.GetManifestAsync(videoUrl);
        }

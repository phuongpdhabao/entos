        /// <summary>
        ///   Download content from Youtube ( isVideo = true: Download Video has Audio, isVideo = false: Download only Audio, isVideo = null: Download silent Video)
        /// </summary>
        /// <summary>
        /// Tải nội dung từ YouTube
        /// </summary>
        /// <param name="videoUrl">URL video YouTube</param>
        /// <param name="saveFolder">Thư mục lưu file</param>
        /// <param name="isVideo">True: tải video có âm thanh, False: chỉ tải âm thanh, null: tải video không âm thanh</param>
        /// <param name="isSubtitle">True: tải phụ đề, False: kiểm tra phụ đề cuối</param>
        /// <returns>Đường dẫn file đã tải</returns>
        public static string DownloadFromYoutube(string videoUrl, string saveFolder, bool? isVideo = true, bool? isSubtitle = null)
        {
            var downloadTask = System.Threading.Tasks.Task.Run(() => DownloadFromYoutubeAsync(videoUrl, saveFolder, isVideo, isSubtitle));
            downloadTask.Wait();
            return downloadTask.Result;

        }


        /// <summary>
        ///   Download content from Youtube ( isVideo = true: Download Video has Audio, isVideo = false: Download only Audio, isVideo = null: Download silent Video, subtitle = true : Download Subtile, subtitle = false : Check EndSubtile)
        /// </summary>
        public static async System.Threading.Tasks.Task<string> DownloadFromYoutubeAsync(string videoUrl, string saveFolder, bool? isVideo = true, bool? subtitle = null)
        {
            var youtube = new YoutubeExplode.YoutubeClient();
            var videoId = YoutubeExplode.Videos.VideoId.Parse(videoUrl);
            var videoYoutube = await youtube.Videos.GetAsync(videoId);
            if (subtitle != null)
            {
                var trackManifest = await youtube.Videos.ClosedCaptions.GetManifestAsync(videoUrl);
                //2024-08-20: Chỉ lấy phụ đề có sãn, không lấy phụ đè tự sinh
                var trackInfo = trackManifest.Tracks?.FirstOrDefault(x => !x.IsAutoGenerated && x.Language.Code == "en");
                if (subtitle == false)
                {
                    if (trackInfo != null)
                        return trackInfo.Url;
                    else return null;
                }
                if (subtitle == true)
                {
                    if (trackInfo is null)
                        trackInfo = trackManifest.Tracks?.FirstOrDefault();
                    if (trackInfo != null)
                    {
                        var subTitlePath = $"{saveFolder}\\{System.Text.RegularExpressions.Regex.Replace(videoYoutube.Title, @"[^a-zA-Z0-9]", "")}.srt";
                        await youtube.Videos.ClosedCaptions.DownloadAsync(trackInfo, subTitlePath);
                        return subTitlePath;
                    }
                }

                return null;
            }
            var streamManifest = await youtube.Videos.Streams.GetManifestAsync(videoId);
            //var streamInfo = streamManifest.GetMuxedStreams().GetWithHighestVideoQuality();
            if (isVideo == null)
            {
                var videoStreamInfo = streamManifest.GetVideoStreams().Where(s => s.Container == YoutubeExplode.Videos.Streams.Container.Mp4).GetWithHighestVideoQuality();
                // Get the actual stream
                var videostream = await youtube.Videos.Streams.GetAsync(videoStreamInfo);
                var videoPath = $"{saveFolder}\\{System.Text.RegularExpressions.Regex.Replace(Module.Helpers.TextHelper.RemoveUnicode(videoYoutube.Title), @"[^a-zA-Z0-9]", "")}-Video.{videoStreamInfo.Container}";
                await youtube.Videos.Streams.DownloadAsync(videoStreamInfo, videoPath);
                return videoPath;
            }
            else if (isVideo == false)
            {
                var audioStreamInfo = streamManifest.GetAudioOnlyStreams().Where(s => s.Container == YoutubeExplode.Videos.Streams.Container.Mp4 || s.Container == YoutubeExplode.Videos.Streams.Container.Mp3).GetWithHighestBitrate();
                // Get the actual stream
                var audiostream = await youtube.Videos.Streams.GetAsync(audioStreamInfo);
                var audioPath = $"{saveFolder}\\{System.Text.RegularExpressions.Regex.Replace(Module.Helpers.TextHelper.RemoveUnicode(videoYoutube.Title), @"[^a-zA-Z0-9]", "")}-Audio.{audioStreamInfo.Container}";
                await youtube.Videos.Streams.DownloadAsync(audioStreamInfo, audioPath);
                return audioPath;
            }
            else
            {
                //video
                var videoStreamInfo = streamManifest.GetVideoStreams().Where(s => s.Container == YoutubeExplode.Videos.Streams.Container.Mp4).GetWithHighestVideoQuality();
                var videostream = await youtube.Videos.Streams.GetAsync(videoStreamInfo);
                var videoPath = $"{saveFolder}\\{System.Text.RegularExpressions.Regex.Replace(Module.Helpers.TextHelper.RemoveUnicode(videoYoutube.Title), @"[^a-zA-Z0-9]", "")}.{videoStreamInfo.Container}";
                //audio
                var audioStreamInfo = streamManifest.GetAudioOnlyStreams().Where(s => s.Container == YoutubeExplode.Videos.Streams.Container.Mp4 || s.Container == YoutubeExplode.Videos.Streams.Container.Mp3).GetWithHighestBitrate();
                var audiostream = await youtube.Videos.Streams.GetAsync(audioStreamInfo);
                //var audioPath = $"{saveFolder}\\{videoYoutube.Title}.{audioStreamInfo.Container}";
                //Trộn 2 luồng               
                var streamInfos = new YoutubeExplode.Videos.Streams.IStreamInfo[] { audioStreamInfo, videoStreamInfo };

                await youtube.Videos.DownloadAsync(streamInfos, new YoutubeExplode.Converter.ConversionRequestBuilder(videoPath).Build());
                return videoPath;
            }
            //var trackManifest = await youtube.Videos.ClosedCaptions.GetManifestAsync(videoUrl);

        }



		        private System.Collections.Generic.Dictionary<string, bool> _cacheAppearanceDisableDelete;
		[Browsable(false)]
        public bool AppearanceDisableDelete
        {
            get
            {

                if (Session.IsNewObject(this))
                    return false;
				if (CampaignContacts.IsLoaded)
                {
                    if (CampaignContacts.Any())
                            return true;
                }else
                {
                    if (_cacheAppearanceDisableDelete is null)
                        _cacheAppearanceDisableDelete = new Dictionary<string, bool>();
                    if (_cacheAppearanceDisableDelete.ContainsKey(nameof(CampaignContacts)))
                    {
                        if (_cacheAppearanceDisableDelete[nameof(CampaignContacts)])
                            return true;
                    }
                    else
                    {
                        //if (Session.FindObject<Module.BusinessObjects.MessageContact>(CriteriaOperator.Parse("[Campaign.Oid] = ?", Oid)) != null) //Loại này sẽ lấy cá tham chiếu
                        bool campaigncontacts = Session.Query<Module.BusinessObjects.MessageContact>().Where(x => x.Campaign.Oid == Oid).Take(1).Any(); //Tạo truy vấn top 1
                        _cacheAppearanceDisableDelete.Add(nameof(CampaignContacts), campaigncontacts);
                        if (campaigncontacts)
                            return true;

                    }                    
                }				
				if (CampaigneChannels.IsLoaded)
                {
                    if (CampaigneChannels.Any())
                            return true;
                }else
                {
                    if (_cacheAppearanceDisableDelete is null)
                        _cacheAppearanceDisableDelete = new Dictionary<string, bool>();
                    if (_cacheAppearanceDisableDelete.ContainsKey(nameof(CampaigneChannels)))
                    {
                        if (_cacheAppearanceDisableDelete[nameof(CampaigneChannels)])
                            return true;
                    }
                    else
                    {
                        //if (Session.FindObject<Module.BusinessObjects.MessageChannel>(CriteriaOperator.Parse("[MarketingCampaign.Oid] = ?", Oid)) != null) //Loại này sẽ lấy cá tham chiếu
                        bool campaignechannels = Session.Query<Module.BusinessObjects.MessageChannel>().Where(x => x.MarketingCampaign.Oid == Oid).Take(1).Any(); //Tạo truy vấn top 1
                        _cacheAppearanceDisableDelete.Add(nameof(CampaigneChannels), campaignechannels);
                        if (campaignechannels)
                            return true;

                    }                    
                }				
                                
                return false;
            }
        }


		[Browsable(false)]
        public bool AppearanceDisableDelete
        {
            get
            {

                if (Session.IsNewObject(this))
                    return false;
				if (DictionaryWordList.IsLoaded)
                {
                    if (DictionaryWordList.Any())
                            return true;
                }else
                {
                    if (_cacheAppearanceDisableDelete is null)
                        _cacheAppearanceDisableDelete = new Dictionary<string, bool>();
                    if (_cacheAppearanceDisableDelete.ContainsKey(nameof(DictionaryWordList)))
                    {
                        if (_cacheAppearanceDisableDelete[nameof(DictionaryWordList)])
                            return true;
                    }
                    else
                    {
                        //if (Session.FindObject<Module.BusinessObjects.DictionaryWord>(CriteriaOperator.Parse("[Dictionary.Oid] = ?", Oid)) != null) //Loại này sẽ lấy cá tham chiếu
                        bool dictionarywordlist = Session.Query<Module.BusinessObjects.DictionaryWord>().Where(x => x.Dictionary.Oid == Oid).Take(1).Any(); //Tạo truy vấn top 1
                        _cacheAppearanceDisableDelete.Add(nameof(DictionaryWordList), dictionarywordlist);
                        if (dictionarywordlist)
                            return true;

                    }                    
                }				
                                
                return false;
            }
        }

